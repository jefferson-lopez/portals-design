export type StripeConnectCountry =
  (typeof STRIPE_CONNECT_COUNTRY_CODES)[number];

export function getCountryFlag(countryCode: string): string {
  return countryCode
    .trim()
    .toUpperCase()
    .replace(/[^A-Z]/g, "")
    .slice(0, 2)
    .replace(/./g, (character) =>
      String.fromCodePoint(127397 + character.charCodeAt(0)),
    );
}

export function isStripeConnectCountry(
  value: string,
): value is StripeConnectCountry {
  return (STRIPE_CONNECT_COUNTRY_CODES as readonly string[]).includes(value);
}
